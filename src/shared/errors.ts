/** 错误码 → HTTP 状态码。未列出的错误按 500 处理。 */
export function httpStatusFor(code: ErrorCode): number {
  if (BAD_REQUEST.has(code)) return 400;
  if (UNAUTHORIZED.has(code)) return 401;
  if (FORBIDDEN.has(code)) return 403;
  if (NOT_FOUND.has(code)) return 404;
  if (CONFLICT.has(code)) return 409;
  if (code === ERROR_CODES.CHAT_RATE_LIMITED) return 429;
  return 500;
}

export interface ErrorEnvelope {
  error: {
    code: ErrorCode;
    message: string;
    requestId?: string;
  };
}

/** 领域/应用错误；message 必须是不含敏感数据的稳定文案。 */
export class AppError extends Error {
  readonly code: ErrorCode;
  readonly status: number;

  constructor(code: ErrorCode, message: string) {
    super(message);
    this.name = 'AppError';
    this.code = code;
    this.status = httpStatusFor(code);
  }
}

export function isAppError(value: unknown): value is AppError {
  return value instanceof AppError;
}

/**
 * 把任意异常收敛为安全错误信封。
 * 未知异常只暴露 INTERNAL_ERROR，不把堆栈、SQL 或输入回显给客户端。
 */
export function toErrorEnvelope(
  error: unknown,
  requestId?: string,
): { status: number; body: ErrorEnvelope } {
  if (isAppError(error)) {
    return {
      status: error.status,
      body: { error: { code: error.code, message: error.message, requestId } },
    };
  }
  return {
    status: 500,
    body: {
      error: {
        code: ERROR_CODES.INTERNAL_ERROR,
        message: '服务器内部错误',
        requestId,
      },
    },
  };
}
